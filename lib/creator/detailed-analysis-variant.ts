import { sprintTermsSchema, type SprintTerms } from './sprints'

// Copy the live brief, bonuses and audience rules; adjust only these milestones.
export function detailedAnalysisVariantTerms(source: SprintTerms, sourceCampaignId: string): SprintTerms {
  const terms = structuredClone(source)
  terms.mgcSourceCampaignId = sourceCampaignId
  for (const views of [50_000, 100_000, 300_000]) {
    if (!terms.milestones.some(item => item.views === views)) throw new Error(`Expected detailed analysis milestone: ${views}`)
  }
  terms.milestones = terms.milestones.filter(item => item.views !== 300_000).map(item => {
    const amountCents = item.views === 50_000 ? 3000 : item.views === 100_000 ? 6500 : item.amountCents
    if (amountCents === item.amountCents) return item
    return { ...item, amountCents, audienceRates: item.audienceRates?.map(rate => ({ ...rate, amountCents: Math.round(rate.amountCents * amountCents / item.amountCents) })) }
  })
  return sprintTermsSchema.parse(terms)
}

export const MGC_CAMPAIGN_NAME = 'Mogging Detailed Analysis MGC'
export const MGC_SUBMISSION_GUIDANCE = 'MGC stands for Mogging Generated Content. Use this campaign to submit content generated by Mogging Admin.'
