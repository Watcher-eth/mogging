const regionNames = new Map<string, string>(usRegionOptions)
const countryNames = new Map<string, string>(countryOptions.map(({ code, label }) => [code, label]))

export function formatProfileLocation(country?: string | null, state?: string | null) {
  if (country === 'US' && state) return `${regionNames.get(state) ?? state}, US`
  if (country) return countryNames.get(country) ?? country
  return null
}
