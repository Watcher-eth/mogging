import { resolve } from 'node:path'

const source = resolve(import.meta.dir, '../../mogging-mobile/src/lib/mogging-icons.ts')
const destination = resolve(import.meta.dir, '../lib/design/mogging-icons.ts')
const content = '// Generated by bun scripts/sync-mogging-icons.ts.\n' + await Bun.file(source).text()

if (process.argv.includes('--check')) {
  if (await Bun.file(destination).text() !== content) throw new Error('Mogging icons are out of sync. Run bun scripts/sync-mogging-icons.ts.')
} else {
  await Bun.write(destination, content)
}

await syncNativeTabIcons()

async function syncNativeTabIcons() {
  const { mkdir } = await import('node:fs/promises')
  const { default: sharp } = await import('sharp')
  const { getMoggingGlyph, moggingIconAccentOpacity, moggingIconGrid, moggingIconStroke } = await import(source)
  const directory = resolve(import.meta.dir, '../../mogging-mobile/assets/icons')
  const check = process.argv.includes('--check')
  if (!check) await mkdir(directory, { recursive: true })

  for (const name of ['home', 'protocol', 'courses'] as const) {
    const { ink, accent } = getMoggingGlyph(name)
    for (const selected of [false, true]) {
      const prefix = name + (selected ? '-selected' : '')
      for (const scale of [1, 2, 3]) {
        const pixels = moggingIconGrid * scale
        const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${pixels}" height="${pixels}" viewBox="0 0 ${moggingIconGrid} ${moggingIconGrid}">
          ${selected ? `<path d="${accent}" opacity="${moggingIconAccentOpacity}"/>` : ''}
          <path d="${ink}" fill="none" stroke="black" stroke-width="${selected ? moggingIconStroke + .12 : moggingIconStroke}" stroke-linejoin="round" stroke-linecap="round"/>
        </svg>`
        const filename = resolve(directory, `${prefix}${scale === 1 ? '' : `@${scale}x`}.png`)
        const image = sharp(Buffer.from(svg)).png()
        if (check) {
          if (!Buffer.from(await Bun.file(filename).arrayBuffer()).equals(await image.toBuffer())) {
            throw new Error(`Native tab icon is out of sync. Run bun scripts/sync-mogging-icons.ts (${filename}).`)
          }
        } else await image.toFile(filename)
      }
    }
  }
}
